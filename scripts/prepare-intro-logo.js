import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';

export function prepareIntroLogo(source){
 if(!/viewBox="0 0 439 217"/.test(source)||/<(?:script|foreignObject|image)\b|\son\w+=|(?:href|xlink:href)="(?!#)/i.test(source))throw Error('Unexpected logo source');
 const original=source.match(/<style>([\s\S]*?)<\/style>/)?.[1];if(!original)throw Error('Missing logo animation');
 const frames=[...original.matchAll(/@keyframes (\w+)\{[\s\S]*?100\.000%\{([^}]+)\}\}/g)];
 const final=new Map(frames.map(m=>[m[1],m[2]])),rules=[...original.matchAll(/\.(\w+)\{animation:(\w+) 4440ms linear infinite;\}/g)];
 if(rules.length<30||rules.some(r=>!final.has(r[2])))throw Error('Incomplete logo animation');
 let css='#how-brand-svg *{transform-box:view-box}\n';
 for(const f of frames)css+=f[0].replace('@keyframes '+f[1],'@keyframes howBrand_'+f[1])+'\n';
 for(const [,className,name]of rules)css+=`#how-brand-svg .${className}{${final.get(name)}}#how-brand-svg.how-brand-deploy .${className}{animation:howBrand_${name} 4440ms linear 1 both}\n`;
 css+='@media(prefers-reduced-motion:reduce){#how-brand-svg.how-brand-deploy *{animation:none}}';
 let markup=source.replace(/<style>[\s\S]*?<\/style>/,'<style>'+css+'</style>');
 const background=/<rect width="439" height="217" fill="url\(#bg\)"\/>/g;if([...markup.matchAll(background)].length!==1)throw Error('Unexpected logo background');
 markup=markup.replace(background,'').replace('<svg ','<svg id="how-brand-svg" class="how-brand-logo" ');
 for(const [,id]of [...source.matchAll(/\bid="([^"]+)"/g)]){
  markup=markup.replaceAll(`id="${id}"`,`id="howBrand-${id}"`).replaceAll(`href="#${id}"`,`href="#howBrand-${id}"`).replaceAll(`url(#${id})`,`url(#howBrand-${id})`);
 }
 return {markup,sourceHash:createHash('sha256').update(source).digest('hex'),animationCount:rules.length};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const source=fs.readFileSync(new URL('../public/assets/branding/HOW_logo_animation.svg',import.meta.url),'utf8'),result=prepareIntroLogo(source);
 fs.writeFileSync(new URL('../src/data/introLogo.js',import.meta.url),`// Generated by scripts/prepare-intro-logo.js; original SVG is preserved in public/assets/branding.\nexport const LOGO_SOURCE_SHA256=${JSON.stringify(result.sourceHash)};\nexport const LOGO_MARKUP=${JSON.stringify(result.markup)};\n`);
 console.log(JSON.stringify({animations:result.animationCount,sourceHash:result.sourceHash}));
}
